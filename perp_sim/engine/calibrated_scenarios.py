_DEPTH_BTC = {"thick": 12.0000, "thin": 0.5000}
_TIMING = {"early": 0.35, "late": 0.65}

def build_calibrated_scenarios() -> list:
    scenarios = []
    for regime, params in _REGIMES.items():
        for depth_name, depth in _DEPTH_BTC.items():
            for timing_name, frac in _TIMING.items():
                scenarios.append(Scenario(
                    name=f"{regime}-{depth_name}-{timing_name}",
                    regime=regime, shock_frac=frac,
                    bg_depth_btc=depth, **params,
                ))
    return scenarios

CALIBRATED_SCENARIOS = {s.name: s for s in build_calibrated_scenarios()}
